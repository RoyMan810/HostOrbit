#!/usr/bin/env bash
# K-VPN Node Deployer, offline-capable self-extracting bundle.
# Audit source files in this public repository before running as root.
set -Eeuo pipefail
umask 077
for binary in base64 tar awk tail mktemp; do
  command -v "$binary" >/dev/null || { echo "Missing required unpack utility: $binary" >&2; exit 1; }
done
tmp=$(mktemp -d)
trap 'rm -rf -- "$tmp"' EXIT
payload_line=$(awk '/^__KVPN_INSTALL_PAYLOAD_BELOW__$/{print NR+1;exit}' "$0")
[[ -n "$payload_line" ]] || { echo 'Missing installer payload' >&2; exit 1; }
tail -n "+$payload_line" "$0" | base64 -d | tar -xz -C "$tmp"
"$tmp/kvpn-node-deployer/install.sh" "$@"
exit $?
